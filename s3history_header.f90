  status = nf90_def_var(ncid, 'zc', NF90_REAL, (/ dimid_grid_xt, dimid_grid_yt, dimid_tile, dimid_time /), varid_zc)
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, '_FillValue', '9.99e+20f')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'cell_methods', 'time: point')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'long_name', 'nsst sub-layer cooling thickness')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'missing_value', '9.99e+20f')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'output_file', 'cubed_sphere_grid_sfc')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'units', 'm')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'coordinates', 'lon lat')
  if (status /= nf90_noerr) call handle_err(status)
  status = nf90_put_att(ncid, varid_zc, 'grid_mapping', 'cubed_sphere')
  if (status /= nf90_noerr) call handle_err(status)

  ! ========== END DEFINITION MODE & CLOSE FILE ==========
  status = nf90_enddef(ncid)
  if (status /= nf90_noerr) call handle_err(status)
  
  !status = nf90_close(ncid)
  !if (status /= nf90_noerr) call handle_err(status)
  
  print *, 'NetCDF file create & header definition successful: ', trim(filename)
  print *, 'Dimensions: ', 7
  print *, 'Variables: ', 162
  
contains
  
